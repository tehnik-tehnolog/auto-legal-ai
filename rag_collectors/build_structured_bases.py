def normalize_newlines(text: str) -> str:
    """
    Устраняет склеивание слов и заголовков (например: 'ФедерацииРАЗДЕЛ I' -> 'Федерации\\n\\nРАЗДЕЛ I')
    """
    if not text:
        return ""
    
    # Вставляем перенос перед РАЗДЕЛ, ПОДРАЗДЕЛ, Глава, Статья, если они прилипли к предыдущему тексту
    t = re.sub(r'([а-яёА-ЯЁ\.\!\?])(?=(?:РАЗДЕЛ\s+[IVXLCDM]+|ПОДРАЗДЕЛ\s+[IVXLCDM]+|Глава\s+\d+|Статья\s+\d+\.|\d+\.\s+[А-ЯЁ]))', r'\1\n\n', text)
    # Вставляем пробел между строчной буквой и заглавной в слитных словах
    t = re.sub(r'([а-яё])([А-ЯЁ])', r'\1 \2', t)
    # Нормализуем множественные переносы
    t = re.sub(r'\n{3,}', '\n\n', t)
    return t.strip()


